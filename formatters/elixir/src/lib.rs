//! Elixir formatting via `mix format`, Elixir's built-in canonical formatter.
//!
//! `mix format` needs no Mix project: in a bare directory it formats files
//! listed in a `.formatter.exs` in place, and `mix format -` round-trips a
//! single source through stdin/stdout (since Elixir 1.18; older releases used
//! `--stdin NAME`). Both modes read `.formatter.exs` from the working
//! directory, so fama writes one into a scratch directory mapping fama's
//! configuration onto mix format's options (`line_length`).
//!
//! Single files stream through stdin; batches are written to a temp directory
//! and formatted with one in-place invocation, amortizing the BEAM VM startup
//! (~100ms) across every file. When the batched invocation fails — a syntax
//! error anywhere aborts the whole run — each file is retried individually so
//! healthy sources still format and the error names the offending file.

use fama_common::{FileType, FormatConfig};
use std::fs;
use std::io::Write;
use std::process::{Command, Stdio};
use tempfile::TempDir;

/// Prefix for source files written into the scratch directory.
const INPUT_PREFIX: &str = "fama_";
/// Extension assumed for batched sources; parsing is identical for `.ex`.
const INPUT_EXT: &str = "ex";

/// Line width fama enforces, mapped to mix format's `:line_length`.
fn line_length() -> u16 {
	FormatConfig::default().line_width
}

/// The `.formatter.exs` written into scratch directories so that `mix format`
/// picks up fama's configuration instead of its defaults. `inputs` is only
/// meaningful for batch mode; stdin mode reads the other options.
fn formatter_exs(inputs: Option<&str>) -> String {
	let inputs = inputs
		.map(|inputs| format!("\tinputs: {},\n", inputs))
		.unwrap_or_default();

	format!(
		"# Generated by fama. Do not edit.\n[\n{}\tline_length: {}\n]\n",
		inputs,
		line_length()
	)
}

/// Format Elixir source (single file) via `mix format -` (stdin → stdout).
pub fn format_elixir(source: &str, _path: &str) -> Result<String, String> {
	let dir = scratch_dir()?;
	fs::write(dir.path().join(".formatter.exs"), formatter_exs(None))
		.map_err(|error| {
			format!("Failed to write .formatter.exs for mix format: {}", error)
		})?;

	let mut child = Command::new("mix")
		.args(["format", "-"])
		.current_dir(dir.path())
		.stdin(Stdio::piped())
		.stdout(Stdio::piped())
		.stderr(Stdio::piped())
		.spawn()
		.map_err(mix_spawn_error)?;

	child
		.stdin
		.as_mut()
		.ok_or_else(|| "mix format stdin was not available".to_string())?
		.write_all(source.as_bytes())
		.map_err(|error| format!("Failed to write to mix format stdin: {}", error))?;

	let output = child
		.wait_with_output()
		.map_err(|error| format!("Failed to wait for mix format: {}", error))?;

	if !output.status.success() {
		return Err(mix_failure_message(&output));
	}

	String::from_utf8(output.stdout)
		.map_err(|error| format!("mix format output was not valid UTF-8: {}", error))
}

/// Format a batch of Elixir sources with a single `mix format` invocation.
pub fn format_batch(contents: &[&str]) -> Vec<Result<String, String>> {
	if contents.is_empty() {
		return Vec::new();
	}

	match format_batch_together(contents) {
		Ok(results) => results,
		// A syntax error anywhere aborts the batched run: retry each file on
		// its own so healthy sources still format and errors stay isolated.
		Err(()) => contents
			.iter()
			.map(|source| format_elixir(source, "input.ex"))
			.collect(),
	}
}

/// One `mix format` run over every source written into a scratch directory.
/// `Ok` results align with `contents`; `Err(())` means the run as a whole
/// failed (infrastructure or any syntax error), triggering per-file fallback.
fn format_batch_together(
	contents: &[&str],
) -> Result<Vec<Result<String, String>>, ()> {
	let dir = scratch_dir().map_err(|_| ())?;

	let names: Vec<String> = (0..contents.len())
		.map(|index| format!("{}{:04}.{}", INPUT_PREFIX, index, INPUT_EXT))
		.collect();

	for (name, source) in names.iter().zip(contents) {
		fs::write(dir.path().join(name), source).map_err(|_| ())?;
	}

	fs::write(
		dir.path().join(".formatter.exs"),
		formatter_exs(Some("[\"fama_*.ex\"]")),
	)
	.map_err(|_| ())?;

	let output = Command::new("mix")
		.arg("format")
		.current_dir(dir.path())
		.output()
		.map_err(|_| ())?;

	if !output.status.success() {
		return Err(());
	}

	names
		.iter()
		.map(|name| {
			fs::read_to_string(dir.path().join(name))
				.map_err(|_| ())
				.map(Ok)
		})
		.collect()
}

fn scratch_dir() -> Result<TempDir, String> {
	TempDir::new()
		.map_err(|error| format!("Failed to create temp dir for mix format: {}", error))
}

fn mix_spawn_error(error: std::io::Error) -> String {
	if error.kind() == std::io::ErrorKind::NotFound {
		return "mix CLI was not found in PATH. Install Elixir to format this language."
			.to_string();
	}

	format!("Failed to start mix format: {}", error)
}

fn mix_failure_message(output: &std::process::Output) -> String {
	let stderr = String::from_utf8_lossy(&output.stderr);
	let stdout = String::from_utf8_lossy(&output.stdout);
	let detail = if stderr.trim().is_empty() {
		stdout.trim()
	} else {
		stderr.trim()
	};

	if detail.is_empty() {
		format!("mix format failed with status {}", output.status)
	} else {
		format!("mix format failed: {}", detail)
	}
}

/// Format a file based on its file type
pub fn format_file(
	source: &str,
	file_path: &str,
	file_type: FileType,
) -> Result<String, String> {
	match file_type {
		FileType::Elixir => format_elixir(source, file_path),
		_ => Err(format!(
			"File type {:?} is not supported by the elixir formatter",
			file_type
		)),
	}
}

#[cfg(test)]
mod tests {
	use super::*;

	/// Skip gracefully when `mix` is unavailable so CI without Elixir stays green.
	fn mix_available() -> bool {
		match Command::new("mix").arg("--version").output() {
			Ok(output) => output.status.success(),
			Err(error) => {
				eprintln!("skipping: mix not usable on PATH ({})", error);
				false
			}
		}
	}

	#[test]
	fn test_format_defmodule_with_pipes() {
		if !mix_available() {
			return;
		}

		let input = "defmodule Server do\ndef handle(req,opts) do\nreq\n|>validate(opts)\n|>render()\nend\nend";
		let output = format_elixir(input, "server.ex").unwrap();

		assert!(output.contains("defmodule Server do"));
		assert!(output.contains("|> validate(opts)"));
		assert!(output.starts_with("defmodule Server do\n"));
	}

	#[test]
	fn test_format_structs_and_pattern_matching() {
		if !mix_available() {
			return;
		}

		let input = "defmodule User do\ndefstruct [:name,age: 0]\ndef adult?(%User{age: age}) when age >= 18, do: true\ndef adult?(_),do: false\nend";
		let output = format_elixir(input, "user.ex").unwrap();

		assert!(output.contains("defstruct [:name, age: 0]"));
		assert!(output.contains("def adult?(%User{age: age}) when age >= 18,"));
		assert!(output.contains("def adult?(_), do: false"));
	}

	#[test]
	fn test_format_sigils() {
		if !mix_available() {
			return;
		}

		let input = "words = ~w(foo bar baz)\ntext = ~s{hello world}\n";
		let output = format_elixir(input, "sigils.ex").unwrap();

		assert!(output.contains("~w(foo bar baz)"));
		assert!(output.contains("~s{hello world}"));
	}

	#[test]
	fn test_format_is_idempotent() {
		if !mix_available() {
			return;
		}

		let input = "defmodule M do\ndef f(x) do\nx|>g(1)\n|>h()\nend\nend";
		let once = format_elixir(input, "m.ex").unwrap();
		let twice = format_elixir(&once, "m.ex").unwrap();

		assert_eq!(once, twice);
	}

	#[test]
	fn test_respects_line_length() {
		if !mix_available() {
			return;
		}

		let long_call = "defmodule Long do\ndef go do\nSome.Module.function_call(arg_one,arg_two,arg_three,arg_four,arg_five)\nend\nend";
		let output = format_elixir(long_call, "long.ex").unwrap();

		// fama's 80-column line length should break the call across lines.
		assert!(
			output.lines().all(|line| line.chars().count() <= 80),
			"every line should fit in 80 columns:\n{}",
			output
		);
		assert!(output.contains("arg_one,"));
	}

	#[test]
	fn test_syntax_error_is_reported() {
		if !mix_available() {
			return;
		}

		let result = format_elixir("defmodule Broken do\ndef f( do\nend", "broken.ex");
		assert!(result.is_err());
		let message = result.unwrap_err();
		assert!(message.contains("mix format failed"), "{}", message);
	}

	#[test]
	fn test_format_file_dispatch() {
		if mix_available() {
			assert!(format_file("x = 1", "a.ex", FileType::Elixir).is_ok());
		}

		let result = format_file("x = 1", "a.txt", FileType::Unknown);
		assert!(result.is_err());
	}

	#[test]
	fn test_batch_formats_all_sources() {
		if !mix_available() {
			return;
		}

		let sources = [
			"defmodule A do\ndef f,do: 1\nend",
			"x = [1,2,3]\n",
			"defmodule B do\ndef g,do: :ok\nend",
		];

		let results = format_batch(&sources);

		assert_eq!(results.len(), 3);
		let outputs: Vec<String> = results
			.into_iter()
			.collect::<Result<Vec<_>, _>>()
			.expect("all healthy sources should format");

		assert!(outputs[0].contains("defmodule A do"));
		assert_eq!(outputs[1], "x = [1, 2, 3]\n");
		assert!(outputs[2].contains("defmodule B do"));
	}

	#[test]
	fn test_batch_isolates_errors() {
		if !mix_available() {
			return;
		}

		let sources = [
			"defmodule Good do\ndef f,do: 1\nend",
			"def Broken do\ndef f( do\nend",
		];

		let results = format_batch(&sources);

		assert_eq!(results.len(), 2);
		assert!(results[0].is_ok(), "healthy source should still format");
		assert!(results[1].is_err(), "broken source should report an error");
	}

	#[test]
	fn test_batch_empty() {
		assert!(format_batch(&[]).is_empty());
	}
}
