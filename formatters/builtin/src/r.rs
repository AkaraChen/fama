//! R formatting via Air (batched external CLI wrapper).

use fama_common::{FormatConfig, Formatter, IndentStyle, LineEnding};
use std::env;
use std::fs;
use std::io::Write;
use std::path::Path;
use std::process::{Command, Stdio};

/// Formatter implementation for R via `air`.
pub struct RFormatter;

impl Formatter for RFormatter {
	fn name(&self) -> &'static str {
		"r"
	}

	fn extensions(&self) -> &'static [&'static str] {
		&["R", "r"]
	}

	fn format(&self, content: &str, path: &Path) -> Result<String, String> {
		format_r(content, path.to_str().unwrap_or(""))
	}

	fn supports_batch(&self) -> bool {
		true
	}

	fn format_batch(&self, contents: &[&str]) -> Vec<Result<String, String>> {
		format_batch(contents)
	}
}

pub const AIR_PATH_ENV: &str = "FAMA_AIR_PATH";
const BATCH_PREFIX: &str = "f";

pub fn air_binary() -> String {
	env::var(AIR_PATH_ENV)
		.ok()
		.filter(|path| !path.is_empty())
		.unwrap_or_else(|| "air".to_string())
}

pub fn air_toml_contents(config: &FormatConfig) -> String {
	let indent_style = match config.indent_style {
		IndentStyle::Tabs => "tab",
		IndentStyle::Spaces => "space",
	};

	let line_ending = match config.line_ending {
		LineEnding::Lf => "lf",
		LineEnding::Crlf => "crlf",
	};

	format!(
		r#"# Generated by fama (go-fmt style)
[format]
line-width = {}
indent-width = {}
indent-style = "{}"
line-ending = "{}"
"#,
		config.line_width, config.indent_width, indent_style, line_ending
	)
}

pub fn format_r(source: &str, path: &str) -> Result<String, String> {
	format_single(&air_binary(), source, &stdin_file_name(path))
}

pub fn format_batch(contents: &[&str]) -> Vec<Result<String, String>> {
	if contents.is_empty() {
		return Vec::new();
	}
	if contents.len() == 1 {
		return vec![format_single(&air_binary(), contents[0], "input.R")];
	}

	let air = air_binary();

	let Ok(temp_dir) = write_configured_temp_dir() else {
		return contents
			.iter()
			.map(|_| Err("r formatting: failed to create temp dir".to_string()))
			.collect();
	};

	let names: Vec<String> = (0..contents.len())
		.map(|index| format!("{BATCH_PREFIX}{index}.R"))
		.collect();

	for (name, content) in names.iter().zip(contents) {
		if let Err(error) = fs::write(temp_dir.path().join(name), content) {
			return contents
				.iter()
				.map(|_| {
					Err(format!(
						"r formatting: failed to write temp file: {error}"
					))
				})
				.collect();
		}
	}

	let output = Command::new(&air)
		.arg("format")
		.arg("--no-color")
		.args(&names)
		.current_dir(temp_dir.path())
		.output();

	match output {
		Ok(output) if output.status.success() => names
			.iter()
			.map(|name| {
				fs::read_to_string(temp_dir.path().join(name)).map_err(|error| {
					format!("r formatting: failed to read air output: {error}")
				})
			})
			.collect(),
		Err(error) if error.kind() == std::io::ErrorKind::NotFound => {
			let msg = command_error(&air, error);
			(0..contents.len()).map(|_| Err(msg.clone())).collect()
		}
		Ok(_) | Err(_) => {
			let mid = contents.len() / 2;
			let (left, right) = std::thread::scope(|s| {
				let h = s.spawn(|| format_batch(&contents[..mid]));
				let right = format_batch(&contents[mid..]);
				let left = h.join().expect("air bisect thread panicked");
				(left, right)
			});
			let mut combined = left;
			combined.extend(right);
			combined
		}
	}
}

fn format_single(
	air: &str,
	source: &str,
	file_name: &str,
) -> Result<String, String> {
	let temp_dir = write_configured_temp_dir()?;
	let stdin_file = temp_dir.path().join(file_name);

	let mut command = Command::new(air);
	command
		.arg("format")
		.arg("--no-color")
		.arg("--stdin-file-path")
		.arg(&stdin_file)
		.current_dir(temp_dir.path())
		.stdin(Stdio::piped())
		.stdout(Stdio::piped())
		.stderr(Stdio::piped());

	let mut child = command.spawn().map_err(|error| command_error(air, error))?;

	child
		.stdin
		.as_mut()
		.ok_or_else(|| "air stdin was not available".to_string())?
		.write_all(source.as_bytes())
		.map_err(|error| format!("Failed to write to air stdin: {error}"))?;

	let output = child
		.wait_with_output()
		.map_err(|error| format!("Failed to wait for air: {error}"))?;

	success_output(output)
}

fn write_configured_temp_dir() -> Result<tempfile::TempDir, String> {
	let temp_dir = tempfile::tempdir().map_err(|error| {
		format!("r formatting: failed to create temp dir: {error}")
	})?;

	fs::write(
		temp_dir.path().join("air.toml"),
		air_toml_contents(&FormatConfig::default()),
	)
	.map_err(|error| {
		format!("r formatting: failed to write air.toml: {error}")
	})?;

	Ok(temp_dir)
}

fn stdin_file_name(path: &str) -> String {
	Path::new(path)
		.file_name()
		.map(|name| name.to_string_lossy().into_owned())
		.filter(|name| name.to_ascii_lowercase().ends_with(".r"))
		.unwrap_or_else(|| "input.R".to_string())
}

fn success_output(output: std::process::Output) -> Result<String, String> {
	if !output.status.success() {
		let stderr = String::from_utf8_lossy(&output.stderr);
		let stdout = String::from_utf8_lossy(&output.stdout);
		let detail = if stderr.trim().is_empty() {
			stdout.trim()
		} else {
			stderr.trim()
		};

		return if detail.is_empty() {
			Err(format!("air failed with status {}", output.status))
		} else {
			Err(format!(
				"air failed with status {}: {detail}",
				output.status
			))
		};
	}

	String::from_utf8(output.stdout)
		.map_err(|error| format!("air output was not valid UTF-8: {error}"))
}

fn command_error(air: &str, error: std::io::Error) -> String {
	if error.kind() == std::io::ErrorKind::NotFound {
		return format!(
			"air CLI was not found in PATH. Install `air` (https://posit-dev.github.io/air) \
			 to format R files, or point {AIR_PATH_ENV} at the binary."
		);
	}

	format!("Failed to start air (`{air}`): {error}")
}

#[cfg(test)]
mod tests {
	use super::*;
	use std::path::PathBuf;

	const SAMPLES: &[&str] = &[
		concat!(
			"result<-df|>select(name,age,salary,department,location)|>",
			"filter(age>30)|>mutate(bonus=salary*0.1)|>arrange(desc(bonus))\n"
		),
		"y<-data.frame(a=c(1,2),b=c(3,4))\n",
		"f<-function(a){\nif(a){\nz<-1\n}\n}\n",
		concat!(
			"p<-ggplot(df,aes(x=x,y=y))+geom_point()+geom_smooth(method=\"lm\")+",
			"labs(title=\"Excess returns\",x=\"Excess return\",y=\"Density\")\n"
		),
	];

	fn require_air() -> Option<String> {
		let air = air_binary();

		let available = Command::new(&air)
			.arg("--version")
			.output()
			.map(|output| output.status.success())
			.unwrap_or(false);

		if available {
			Some(air)
		} else {
			println!(
				"skipping: `air` binary not found; install Air \
				 (https://posit-dev.github.io/air) or set {AIR_PATH_ENV}"
			);
			None
		}
	}

	fn assert_tabs(formatted: &str) {
		assert!(
			formatted.contains('\t'),
			"expected tab indentation from fama config, got: {formatted:?}"
		);
	}

	#[test]
	fn test_air_toml_contents_follows_fama_defaults() {
		let toml = air_toml_contents(&FormatConfig::default());

		assert!(toml.contains("[format]"));
		assert!(toml.contains("line-width = 80"));
		assert!(toml.contains("indent-width = 4"));
		assert!(toml.contains("indent-style = \"tab\""));
		assert!(toml.contains("line-ending = \"lf\""));
	}

	#[test]
	fn test_air_binary_env_override_documented() {
		assert!(!air_binary().is_empty());
		if env::var(AIR_PATH_ENV).is_ok_and(|path| !path.is_empty()) {
			assert_eq!(air_binary(), env::var(AIR_PATH_ENV).unwrap());
		}
	}

	#[test]
	fn test_format_r_samples() {
		let Some(_air) = require_air() else {
			return;
		};

		let formatted = format_r(SAMPLES[1], "frame.R").unwrap();
		assert_eq!(
			formatted, "y <- data.frame(a = c(1, 2), b = c(3, 4))\n",
			"data.frame constructor should be flattened and spaced"
		);

		let formatted = format_r(SAMPLES[2], "fn.R").unwrap();
		assert_eq!(
			formatted, "f <- function(a) {\n\tif (a) {\n\t\tz <- 1\n\t}\n}\n",
			"function definitions should be braced and tab-indented"
		);

		let formatted = format_r(SAMPLES[0], "pipe.R").unwrap();
		assert_tabs(&formatted);
		assert!(formatted.contains("result <- df |>"));
		assert!(formatted.contains("\tfilter(age > 30) |>"));
		assert!(formatted.contains("desc(bonus)"));

		let formatted = format_r(SAMPLES[3], "plot.R").unwrap();
		assert_tabs(&formatted);
		assert!(formatted.contains("p <- ggplot(df, aes(x = x, y = y)) +"));
		assert!(formatted.contains("\tgeom_smooth(method = \"lm\") +"));
	}

	#[test]
	fn test_format_r_preserves_semantics_and_stdin_name() {
		let Some(_air) = require_air() else {
			return;
		};

		let formatted = format_r("x   <-   1+2*3\n", "notes.txt").unwrap();
		assert_eq!(formatted, "x <- 1 + 2 * 3\n");
	}

	#[test]
	fn test_format_r_is_idempotent() {
		let Some(_air) = require_air() else {
			return;
		};

		for sample in SAMPLES {
			let once = format_r(sample, "sample.R").unwrap();
			let twice = format_r(&once, "sample.R").unwrap();
			assert_eq!(once, twice, "formatting must be idempotent for:\n{sample}");
		}
	}

	#[test]
	fn test_format_batch_formats_all_files() {
		let Some(_air) = require_air() else {
			return;
		};

		let results = format_batch(SAMPLES);

		assert_eq!(results.len(), SAMPLES.len());
		for (result, sample) in results.iter().zip(SAMPLES) {
			let formatted = result
				.as_ref()
				.unwrap_or_else(|error| panic!("batch entry must format: {error}"));
			assert_ne!(formatted, sample, "input was left unformatted");
		}

		for (index, sample) in SAMPLES.iter().enumerate() {
			let single = format_r(sample, "sample.R").unwrap();
			assert_eq!(results[index].as_deref(), Ok(single.as_str()));
		}

		assert_tabs(results[0].as_deref().unwrap());
		assert_eq!(
			results[1].as_deref(),
			Ok("y <- data.frame(a = c(1, 2), b = c(3, 4))\n")
		);
		assert_eq!(
			results[2].as_deref(),
			Ok("f <- function(a) {\n\tif (a) {\n\t\tz <- 1\n\t}\n}\n")
		);
		assert_tabs(results[3].as_deref().unwrap());
	}

	#[test]
	fn test_format_batch_aligns_with_inputs() {
		let Some(_air) = require_air() else {
			return;
		};

		let inputs = ["x<-1\n", "y<-2\n", "z<-3\n"];
		let results = format_batch(&inputs);

		assert_eq!(results.len(), inputs.len());
		assert_eq!(
			results.iter().map(|r| r.as_deref().unwrap()).collect::<Vec<_>>(),
			vec!["x <- 1\n", "y <- 2\n", "z <- 3\n"]
		);
	}

	#[test]
	fn test_format_batch_error_isolation() {
		let Some(_air) = require_air() else {
			return;
		};

		let garbage = "this is (not valid R <<<\n";
		let inputs = ["x<-1\n", garbage, "y<-2\n"];
		let results = format_batch(&inputs);

		assert_eq!(results.len(), inputs.len());
		assert_eq!(results[0].as_deref(), Ok("x <- 1\n"));
		assert!(results[1].is_err(), "syntax garbage must produce Err");
		assert_eq!(results[2].as_deref(), Ok("y <- 2\n"));
	}

	#[test]
	fn test_format_r_error_isolation() {
		let Some(_air) = require_air() else {
			return;
		};

		let error = format_r("x <- (\n", "broken.R").unwrap_err();
		assert!(!error.is_empty(), "error should carry a detail message");
		assert!(error.contains("air"), "error should name the formatter");
	}

	#[test]
	fn test_format_batch_empty() {
		assert!(format_batch(&[]).is_empty());
	}

	#[test]
	fn test_stdin_file_name_normalization() {
		assert_eq!(stdin_file_name("R/script.R"), "script.R");
		assert_eq!(stdin_file_name("lower.r"), "lower.r");
		assert_eq!(stdin_file_name("no-extension"), "input.R");
		assert_eq!(stdin_file_name(""), "input.R");
		assert_eq!(
			PathBuf::from(stdin_file_name("nested/dir/plot.R")),
			PathBuf::from("plot.R")
		);
	}
}
